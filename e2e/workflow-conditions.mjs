// Model-free fixtures against the disposable CI Worker only.
export async function workflowConditions({context,web,apiHost,shots}) {
 if(new URL(apiHost).hostname!=='127.0.0.1')throw Error('Workflow condition fixtures require the local test Worker')
 const page=await context.newPage()
 await page.setViewportSize({width:1440,height:1000})
 let previousMode
 const call=(method,path,body)=>page.evaluate(async({method,path,body,apiHost})=>{
  const orgId=localStorage.getItem('orgId'),url=new URL(path,apiHost)
  if(method==='GET')url.searchParams.set('orgId',orgId)
  const response=await fetch(url,{method,headers:{'content-type':'application/json','x-session-token':localStorage.getItem('sessionToken')},body:method==='GET'?undefined:JSON.stringify({...body,orgId})})
  if(!response.ok)throw Error(`Workflow fixture ${method} ${path}: ${response.status}`)
  return response.json()
 },{method,path,body,apiHost})
 try {
  await page.goto(web,{waitUntil:'load'})
  await page.waitForFunction(()=>Boolean(localStorage.getItem('sessionToken')&&localStorage.getItem('orgId')))
  previousMode=(await call('GET','/orgs/mode')).mode
  const {business}=await call('POST','/businesses',{name:`Conditional workflow ${Date.now()}`,private:true})
  await call('PUT','/orgs/mode',{mode:'harness'})
  await page.reload({waitUntil:'load'})
  await page.goto(`${web}#/workflows`,{waitUntil:'load'})
  const screen=page.locator('.shell > .hx-resource-screen')
  await screen.locator('.screen-head').getByRole('button',{name:/^(Set up an automation|オートメーションを設定)$/}).click()
  await screen.getByRole('button',{name:/^(Manual setup|手動で設定)$/}).click()
  const builder=screen.locator('.hx-builder'),name=`Conditional UI ${Date.now()}`
  await builder.getByLabel(/^(Workflow name|ワークフロー名)$/).fill(name)
  await builder.locator('input[placeholder="#ops"]').fill(`#${business.slug}`)
  await builder.locator('textarea').fill('This local fixture must not post for an unmatched condition')
  await builder.getByRole('checkbox',{name:/^(Run\ only\ when\ the\ condition\ matches|条件に合う場合だけ実行)$/}).check()
  await builder.getByLabel(/^(Condition\ field|条件の項目)$/,{exact:true}).fill('amount')
  await builder.getByLabel(/^(Condition\ comparison|条件の比較方法)$/,{exact:true}).selectOption('gte')
  await builder.getByLabel(/^(Comparison\ value|比較する値)$/,{exact:true}).fill('100')
  await builder.getByLabel(/^(Condition\ combination|条件の組み合わせ)$/,{exact:true}).selectOption('all')
  await builder.getByRole('button',{name:/^(Add\ a\ condition|条件を追加)$/,exact:true}).click()
  await builder.getByLabel(/^(Condition\ field|条件の項目)$/,{exact:true}).nth(1).fill('currency')
  await builder.getByLabel(/^(Comparison\ value|比較する値)$/,{exact:true}).nth(1).fill('JPY')
  await page.screenshot({path:`${shots}/workflow-condition-editor.png`})
  await page.setViewportSize({width:390,height:844})
  await builder.getByLabel(/^(Comparison\ value|比較する値)$/,{exact:true}).nth(1).scrollIntoViewIfNeeded()
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Condition editor overflows the narrow viewport')
  await page.screenshot({path:`${shots}/workflow-condition-editor-mobile.png`})
  await page.setViewportSize({width:1440,height:1000})
  await builder.getByRole('button',{name:/^(Save workflow|ワークフローを保存)$/}).click()
  const row=screen.locator('[data-workflow]').filter({hasText:name})
  await row.waitFor({state:'visible'})
  const id=await row.getAttribute('data-workflow')
  const expected={all:[{path:['input','amount'],op:'gte',value:100},{path:['input','currency'],op:'eq',value:'JPY'}]}
  const saved=await call('GET',`/workflows/${id}`)
  if(JSON.stringify(saved.workflow.steps[0].when)!==JSON.stringify(expected))throw Error('Condition editor did not persist its typed expression')
  await row.click()
  await screen.locator('.hx-flow-condition').waitFor({state:'visible'})
  await page.reload({waitUntil:'load'})
  const description=screen.locator('.hx-flow-condition')
  await description.waitFor({state:'visible'})
  const text=await description.innerText()
  if(!text.includes('amount ≥ 100')||!text.includes('currency = "JPY"'))throw Error('Saved conditions are not visible in workflow details')
  await page.screenshot({path:`${shots}/workflow-condition-detail.png`})
  const path=`/channels/messages?channel=${encodeURIComponent(`b:${business.slug}`)}`
  const before=await call('GET',path)
  const {run}=await call('POST',`/workflows/${id}/run`,{input:{amount:10,currency:'JPY'}})
  if(run.definitionRevision!==1)throw Error('Run did not retain its definition revision')
  if(run.status!=='done'||run.log[0]?.status!=='skipped')throw Error('Unmatched condition did not skip its effect')
  const after=await call('GET',path)
  if(JSON.stringify(before.messages)!==JSON.stringify(after.messages))throw Error('Unmatched workflow condition posted a message')
  await page.reload({waitUntil:'load'})
  const runRow=screen.locator(`[data-run="${run.id}"]`)
  await runRow.waitFor({state:'visible'})
  await runRow.getByText(/^(Version 1|バージョン 1)$/).waitFor({state:'visible'})
  if(!await runRow.locator('.hx-status.skipped').isVisible())throw Error('Skipped step is missing from the execution history')
  await runRow.locator('summary').filter({hasText:/Condition did not match|条件に一致しなかったため/}).waitFor({state:'visible'})
  await page.screenshot({path:`${shots}/workflow-condition-run.png`})
  await screen.getByRole('button',{name:/^(Edit workflow|ワークフローを編集)$/}).click()
  await builder.getByLabel(/^(Workflow name|ワークフロー名)$/).fill(`${name} edited`)
  await builder.getByLabel(/^(Comparison value|比較する値)$/,{exact:true}).first().fill('200')
  await builder.getByRole('button',{name:/^(Save workflow|ワークフローを保存)$/}).click()
  await screen.locator('.hx-flow-condition').waitFor({state:'visible'})
  await page.reload({waitUntil:'load'})
  await screen.locator('.screen-head').getByText(`${name} edited`,{exact:true}).waitFor({state:'visible'})
  const edited=await call('GET',`/workflows/${id}`)
  expected.all[0].value=200
  if(JSON.stringify(edited.workflow.steps[0].when)!==JSON.stringify(expected))throw Error('Editing lost or failed to update saved conditions')
  await page.screenshot({path:`${shots}/workflow-condition-edited.png`})
  await screen.getByRole('button',{name:/^(Edit workflow|ワークフローを編集)$/}).click()
  await builder.getByLabel(/^(Trigger|トリガー)$/,{exact:true}).selectOption('schedule')
  await builder.getByLabel(/^(Cadence|頻度)$/,{exact:true}).selectOption('monthly')
  await builder.getByLabel(/^(Day of month|毎月の日付)$/,{exact:true}).selectOption('31')
  await builder.getByLabel(/^(Time zone|タイムゾーン)$/,{exact:true}).fill('Invalid/Zone')
  if(await builder.getByRole('button',{name:/^(Save workflow|ワークフローを保存)$/}).isEnabled())throw Error('Invalid timezone remained savable')
  await builder.getByLabel(/^(Time zone|タイムゾーン)$/,{exact:true}).fill('UTC')
  await page.screenshot({path:`${shots}/workflow-condition-schedule-editor.png`})
  await builder.getByRole('button',{name:/^(Save workflow|ワークフローを保存)$/}).click()
  await screen.locator('.hx-flow-condition').waitFor({state:'visible'})
  const scheduled=await call('GET',`/workflows/${id}`)
  if(scheduled.workflow.trigger.cadence!=='monthly'||scheduled.workflow.trigger.monthday!==31||scheduled.workflow.trigger.timezone!=='UTC')throw Error('Calendar settings were not persisted')
  await call('PUT',`/workflows/${id}`,{enabled:false})
  await page.reload({waitUntil:'load'})
  const history=screen.locator('.hx-workflow-history')
  await history.locator('summary').click()
  await history.getByLabel(/^(Compare from|比較元)$/,{exact:true}).waitFor({state:'visible'})
  const versions=await call('GET',`/workflows/${id}/revisions`)
  if(versions.items.length<4)throw Error('Workflow revision history omitted a saved definition change')
  await history.getByLabel(/^(Compare from|比較元)$/,{exact:true}).selectOption('1')
  await history.getByLabel(/^(Compare to|比較先)$/,{exact:true}).selectOption(String(versions.items[0].revision))
  await history.locator('.hx-revision-changes').waitFor({state:'visible'})
  if(!(await history.innerText()).includes(`${name} edited`))throw Error('Revision comparison did not show the edited name')
  await history.scrollIntoViewIfNeeded()
  await page.screenshot({path:`${shots}/workflow-condition-history.png`})
  await page.setViewportSize({width:390,height:844})
  await history.scrollIntoViewIfNeeded()
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Revision history overflows the narrow viewport')
  await page.screenshot({path:`${shots}/workflow-condition-history-mobile.png`})
  if(await history.locator('pre').count())throw Error('Definition comparison still renders raw JSON')
  await page.setViewportSize({width:1440,height:1000})
  await page.emulateMedia({colorScheme:'dark'})
  await history.scrollIntoViewIfNeeded()
  const historyColors=await history.evaluate(element=>({background:getComputedStyle(element).backgroundColor,color:getComputedStyle(element).color}))
  if(historyColors.background==='rgb(255, 255, 255)'||historyColors.background===historyColors.color)throw Error('History theme has unreadable colors')
  await page.screenshot({path:`${shots}/workflow-condition-history-dark.png`})




 } catch(error) {
  await page.screenshot({path:`${shots}/workflow-condition-failure.png`}).catch(()=>{})
  throw error
 } finally {
  if(previousMode)await call('PUT','/orgs/mode',{mode:previousMode}).catch(()=>{})
  await page.close()
 }
}
